            [-30, -40, -40, -50, -50, -40, -40, -30],
            [-30, -40, -40, -50, -50, -40, -40, -30],
            [-30, -40, -40, -50, -50, -40, -40, -30],
            [-30, -40, -40, -50, -50, -40, -40, -30],
            [-20, -30, -30, -40, -40, -30, -30, -20],
            [-10, -20, -20, -20, -20, -20, -20, -10],
            [20, 20, 0, 0, 0, 0, 20, 20],
            [20, 30, 10, 0, 0, 10, 30, 20],
        ],
    ];

    public function evaluate(Position $p): int
    {
        $score = 0;
        for ($i = 0; $i < 64; ++$i) {
            $square = Square::fromIndex($i);
            $piece = $p->pieceAt($square);
            if ($piece === null) {
                continue;
            }
            $t = $piece->type->value;
            $row = $piece->color === Color::White ? 7 - $square->rank() : $square->rank();
            $value = PieceValues::of($piece->type) + self::TABLES[$t][$row][$square->file()];
            $score += $piece->color === Color::White ? $value : -$value;
        }

        return $score;
    }

    /** Valeur matérielle seule (voir PieceValues). */
    public static function value(PieceType $type): int
    {
        return PieceValues::of($type);
    }
}
